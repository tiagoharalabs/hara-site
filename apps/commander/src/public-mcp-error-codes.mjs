// Only deliberately published, stable symbolic error codes may be reflected in
// the MCP result. Shape checks alone are unsafe: a secret can be uppercase.
const PUBLIC_MCP_ERROR_CODES = new Set([
  "POLICY_DENIED",
  "MCP_PRODUCT_ACCESS_DENIED",
  "GRANT_MISSING",
  "ENTITLEMENT_NOT_ACTIVE",
  "ENTITLEMENT_NOT_FOUND",
  "QUOTA_DENIED",
  "QUOTA_EXCEEDED",
  "IDEMPOTENCY_CONFLICT",
  "DEVICE_AUTH_REQUIRED",
  "DEVICE_AUTH_INVALID",
  "DEVICE_LIMIT_REACHED",
  "DEVICE_PAIRING_INVALID",
  "DEVICE_PAIRING_CREATE_FAILED",
  "DEVICE_ENROLLMENT_ACK_UNKNOWN",
  "DEVICE_ENROLLMENT_CLIENT_TOKEN_INVALID",
  "DEVICE_TRANSPORT_MODE_INVALID",
  "DEVICE_APPROVAL_MODE_INVALID",
  "DEVICE_AUTHORIZATION_FORBIDDEN",
  "DEVICE_AUTHORIZATION_CODE_INVALID",
  "DEVICE_AUTHORIZATION_CODE_ALREADY_USED",
  "DEVICE_ONLINE_CHECK_REQUIRED",
  "AGENT_UPGRADE_REQUIRED",
  "LIST_OFFSET_UNSUPPORTED",
  "UNKNOWN_FUNCTION_ID",
  "CALL_EXECUTION_OUTCOME_UNKNOWN",
  "REQUEST_USAGE_TERMINAL",
]);

export function approvedPublicMcpErrorCode(raw) {
  return typeof raw === "string" && PUBLIC_MCP_ERROR_CODES.has(raw)
    ? raw
    : "COMMANDER_MCP_TOOL_FAILED";
}
